// Script to generate placeholder mount STL files
// Run with: npx tsx scripts/generate-mounts.ts

import * as fs from "fs";
import * as path from "path";

const GRID_SIZE = 42; // mm
const BASE_HEIGHT = 5; // mm (varies by mount type)

interface Triangle {
  normal: [number, number, number];
  vertices: [[number, number, number], [number, number, number], [number, number, number]];
}

function createBox(
  x: number,
  y: number,
  z: number,
  width: number,
  depth: number,
  height: number
): Triangle[] {
  const triangles: Triangle[] = [];

  const x1 = x, y1 = y, z1 = z;
  const x2 = x + width, y2 = y + depth, z2 = z + height;

  // Bottom face (z = z1)
  triangles.push({
    normal: [0, 0, -1],
    vertices: [[x1, y1, z1], [x2, y1, z1], [x2, y2, z1]],
  });
  triangles.push({
    normal: [0, 0, -1],
    vertices: [[x1, y1, z1], [x2, y2, z1], [x1, y2, z1]],
  });

  // Top face (z = z2)
  triangles.push({
    normal: [0, 0, 1],
    vertices: [[x1, y1, z2], [x2, y2, z2], [x2, y1, z2]],
  });
  triangles.push({
    normal: [0, 0, 1],
    vertices: [[x1, y1, z2], [x1, y2, z2], [x2, y2, z2]],
  });

  // Front face (y = y1)
  triangles.push({
    normal: [0, -1, 0],
    vertices: [[x1, y1, z1], [x2, y1, z2], [x2, y1, z1]],
  });
  triangles.push({
    normal: [0, -1, 0],
    vertices: [[x1, y1, z1], [x1, y1, z2], [x2, y1, z2]],
  });

  // Back face (y = y2)
  triangles.push({
    normal: [0, 1, 0],
    vertices: [[x1, y2, z1], [x2, y2, z1], [x2, y2, z2]],
  });
  triangles.push({
    normal: [0, 1, 0],
    vertices: [[x1, y2, z1], [x2, y2, z2], [x1, y2, z2]],
  });

  // Left face (x = x1)
  triangles.push({
    normal: [-1, 0, 0],
    vertices: [[x1, y1, z1], [x1, y2, z1], [x1, y2, z2]],
  });
  triangles.push({
    normal: [-1, 0, 0],
    vertices: [[x1, y1, z1], [x1, y2, z2], [x1, y1, z2]],
  });

  // Right face (x = x2)
  triangles.push({
    normal: [1, 0, 0],
    vertices: [[x2, y1, z1], [x2, y2, z2], [x2, y2, z1]],
  });
  triangles.push({
    normal: [1, 0, 0],
    vertices: [[x2, y1, z1], [x2, y1, z2], [x2, y2, z2]],
  });

  return triangles;
}

function createGridfinityBase(
  height: number,
  lipHeight: number = 2.6,
  tolerance: number = 0.5
): Triangle[] {
  const triangles: Triangle[] = [];
  const size = GRID_SIZE - tolerance;

  // Main body
  triangles.push(...createBox(0, 0, 0, size, size, height - lipHeight));

  // Lip (slightly smaller for nesting)
  const lipInset = 0.8;
  triangles.push(
    ...createBox(
      lipInset,
      lipInset,
      height - lipHeight,
      size - 2 * lipInset,
      size - 2 * lipInset,
      lipHeight
    )
  );

  return triangles;
}

function writeBinaryStl(triangles: Triangle[], filePath: string): void {
  const headerSize = 80;
  const triangleSize = 50; // 12 bytes normal + 36 bytes vertices + 2 bytes attribute
  const bufferSize = headerSize + 4 + triangles.length * triangleSize;

  const buffer = Buffer.alloc(bufferSize);
  let offset = 0;

  // Header (80 bytes)
  buffer.write("Generated by rsfinity mount generator", 0, "utf8");
  offset = 80;

  // Triangle count
  buffer.writeUInt32LE(triangles.length, offset);
  offset += 4;

  // Triangles
  for (const tri of triangles) {
    // Normal
    buffer.writeFloatLE(tri.normal[0], offset);
    buffer.writeFloatLE(tri.normal[1], offset + 4);
    buffer.writeFloatLE(tri.normal[2], offset + 8);
    offset += 12;

    // Vertices
    for (const v of tri.vertices) {
      buffer.writeFloatLE(v[0], offset);
      buffer.writeFloatLE(v[1], offset + 4);
      buffer.writeFloatLE(v[2], offset + 8);
      offset += 12;
    }

    // Attribute byte count
    buffer.writeUInt16LE(0, offset);
    offset += 2;
  }

  fs.writeFileSync(filePath, buffer);
  console.log(`Generated: ${filePath} (${triangles.length} triangles)`);
}

// Generate mount presets
const mountsDir = path.join(process.cwd(), "public", "mounts");
fs.mkdirSync(mountsDir, { recursive: true });

// Gridfinity Original (5mm base)
writeBinaryStl(
  createGridfinityBase(5.0, 2.6, 0.5),
  path.join(mountsDir, "gridfinity-original.stl")
);

// Gridfinity Refined (4.75mm base, tighter tolerances)
writeBinaryStl(
  createGridfinityBase(4.75, 2.4, 0.4),
  path.join(mountsDir, "gridfinity-refined.stl")
);

// Gridfinity Lite (2.8mm, minimal base)
writeBinaryStl(
  createGridfinityBase(2.8, 1.2, 0.5),
  path.join(mountsDir, "gridfinity-lite.stl")
);

// Clickfinity (5.2mm with click mechanism - simplified as box for now)
writeBinaryStl(
  createGridfinityBase(5.2, 2.8, 0.5),
  path.join(mountsDir, "clickfinity.stl")
);

console.log("\nMount STL files generated successfully!");
